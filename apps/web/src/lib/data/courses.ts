export function getCourseBySlug(slug: string) {
  return courses.find((c) => c.slug === slug);
}

export function getFeaturedCourses() {
  return courses.filter((c) => c.featured);
}

export function getCourseCategories() {
  const map = new Map<string, number>();
  for (const c of courses) map.set(c.category, (map.get(c.category) ?? 0) + 1);
  return [...map.entries()].map(([label, count]) => ({ label, count }));
}

export function getRelatedCourses(current: Course, limit = 3) {
  return courses.filter((c) => c.id !== current.id && c.category === current.category).slice(0, limit);
}